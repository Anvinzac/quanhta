const pathOf = new Map(subcategoryOptions.map(option => [option.path[2], option.path]))

const isCapitalised = (word: string) => word[0] !== word[0].toLowerCase()

/** Generic names get the brand ("Dầu ăn" → "Dầu ăn Neptune"); names with their own line name ("Mì Hảo Hảo …") stay as they are. */
const baseName = (name: string, brand: string) =>
  fold(name).includes(fold(brand)) || name.split(' ').slice(1).some(isCapitalised) ? name : `${name} ${brand}`

const flat = Object.entries(bySubcategory).flatMap(([subId, entries]) => {
  const path = pathOf.get(subId)
  if (!path) throw new Error(`Unknown subcategory "${subId}" in product suggestions`)
  return entries.map(([name, brand]) => ({ name: baseName(name, brand), brand, path }))
})
const nameCounts = new Map<string, number>()
for (const item of flat) nameCounts.set(item.name, (nameCounts.get(item.name) ?? 0) + 1)

export const productSuggestions: ProductSuggestion[] = flat.map(item =>
  nameCounts.get(item.name)! > 1 && !fold(item.name).includes(fold(item.brand)) ? { ...item, name: `${item.name} ${item.brand}` } : item)

export const knownBrands = [...new Set(productSuggestions.map(item => item.brand))].sort((a, b) => a.localeCompare(b, 'vi'))

/** Lowercase without Vietnamese diacritics, so "giay an" finds "Giấy ăn". */
export function fold(text: string) {
  return text.normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/đ/g, 'd').replace(/Đ/g, 'd').toLowerCase()
}

const words = (text: string) => fold(text).split(/[^a-z0-9]+/).filter(Boolean)

const indexed = productSuggestions.map(item => {
  const nameWords = words(item.name)
  return { item, nameWords, phrase: nameWords.join(' '), initials: nameWords.map(word => word[0]).join(''), brandWords: words(item.brand) }
})

/**
 * Best matches for what the vendor has typed so far. Matches, best first: the start of the name,
 * the start of any word (all typed words must match), the word initials ("ga" → "Giấy ăn"), anywhere in the name (4+ letters).
 */
export function suggestProducts(query: string, limit = 8): ProductSuggestion[] {
  const tokens = words(query)
  if (!tokens.length) return []
  const typed = tokens.join(' ')
  const compact = tokens.join('')

  const scored: { item: ProductSuggestion, score: number }[] = []
  for (const entry of indexed) {
    let score: number | null = null
    if (entry.phrase.startsWith(typed)) score = 0
    else if (tokens.every(token => entry.nameWords.some(word => word.startsWith(token)) || entry.brandWords.some(word => word.startsWith(token))))
      score = entry.nameWords[0].startsWith(tokens[0]) ? 1 : 2
    else if (compact.length >= 2 && entry.initials.startsWith(compact)) score = 3
    else if (typed.length >= 4 && entry.phrase.includes(typed)) score = 4
    if (score !== null) scored.push({ item: entry.item, score })
  }
  return scored
    .sort((a, b) => a.score - b.score || a.item.name.length - b.item.name.length || a.item.name.localeCompare(b.item.name, 'vi'))
    .slice(0, limit)
    .map(entry => entry.item)
}
